#!/usr/bin/env swipl
:- initialization(main, main).

:- prolog_load_context(directory, Dir),
   directory_file_path(Dir, '..', Root),
   absolute_file_name(Root, Abs),
   asserta(demo_root(Abs)),
   directory_file_path(Abs, 'load.pl', Load),
   use_module(Load).

:- use_module(library(deeds_schema)).
:- use_module(library(deeds_rules)).
:- use_module(library(deeds_report)).
:- use_module(library(filesex)).

main(_Args) :-
    demo_root(Root),
    directory_file_path(Root, 'data', DataDir),
    make_directory_path(DataDir),
    directory_file_path(DataDir, 'demo_scratch.db', DB),
    ignore(catch(delete_file(DB), _, true)),
    setup_deeds(DB),
    run_demo,
    detach_deeds_db,
    ignore(catch(delete_file(DB), _, true)).

run_demo :-
    print_banner,
    nl,
    section('1. Parties on the register'),
    print_parties,
    section('2. Properties on the register'),
    print_properties,
    section('3. current_owner/2 for every property'),
    forall(property(Prop, _, _, _), print_current_owner(Prop)),
    section('4. title_chain/2 — Erf 789 Parktown (two transfers)'),
    print_title_chain(prop_parktown_789),
    section('5. title_chain/2 — Erf 123 Claremont'),
    print_title_chain(prop_claremont_123),
    section('6. is_bonded/2 — bonded and unencumbered properties'),
    print_bonds(prop_claremont_123),
    print_bonds(prop_parktown_789),
    print_bonds(prop_weltevreden_78),
    section('7. properties_owned_by/2'),
    print_owned_by(ayesha),
    print_owned_by(lerato),
    print_owned_by(tm_holdings),
    print_owned_by(mokoena_trust),
    print_owned_by(thabo),
    print_owned_by(pieter),
    section('8. Deed history search by number'),
    print_deed_search('T9100/2024'),
    print_deed_search('T6100/2020'),
    print_deed_search('B1500/2016'),
    print_deed_search('B2100/2021'),
    print_deed_search('K400/2018S'),
    print_deed_search('T99999/2024'),
    section('9. Encumbrance summary per property'),
    forall(property(Prop, _, _, _), print_encumbrances(Prop)),
    section('10. Validation: transfer not from the current owner'),
    writeln('Attempting T99901/2024: Thabo Mokoena transfers Erf 123 Claremont'),
    writeln('(current owner is Lerato Dlamini) ...'),
    register_transfer('T99901/2024', prop_claremont_123, thabo, pieter,
                      '2024-06-01', 2500000, R1),
    print_result(R1), nl,
    section('11. Validation: transfer blocked by an outstanding bond'),
    writeln('Attempting T99902/2024: Lerato Dlamini transfers Erf 123 Claremont'),
    writeln('to Pieter van der Merwe, while bond B2100/2021 is still open ...'),
    register_transfer('T99902/2024', prop_claremont_123, lerato, pieter,
                      '2024-06-01', 2500000, R2),
    print_result(R2), nl,
    section('12. Validation: unique deed numbers and format'),
    writeln('Attempting to reuse existing title number T4521/2021 ...'),
    register_transfer('T4521/2021', prop_claremont_123, lerato, pieter,
                      '2024-06-01', 2500000, R3),
    print_result(R3), nl,
    writeln('Attempting invalid title number X12/24 ...'),
    register_first_title('X12/24', prop_claremont_123, thabo,
                         '2018-03-15', grant, R4),
    print_result(R4), nl,
    section('13. Happy path on a new erf: bond, cancellation, then transfer'),
    writeln('Registering a sixth (demo) erf, opening title, bond, cancellation, transfer ...'),
    register_property(prop_demo_10, erf,
        'Erf 10 Fictional Township, City of Cape Town, Western Cape',
        erf('10', 'Fictional Township', 'City of Cape Town', 'Western Cape', 500),
        RP),
    print_result(RP),
    register_first_title('T5000/2022', prop_demo_10, thabo, '2022-01-20', grant, RT),
    print_result(RT),
    register_bond('B6000/2022', prop_demo_10,
                  'Atlantic Commercial Bank Limited', 800000, '2022-01-20', RB),
    print_result(RB),
    writeln('Transfer while the bond is open (should be blocked):'),
    register_transfer('T5001/2025', prop_demo_10, thabo, lerato,
                      '2025-03-01', 1200000, RBlocked),
    print_result(RBlocked),
    cancel_bond('B6000/2022', '2025-02-20', RC),
    print_result(RC),
    writeln('Transfer after cancellation (should succeed):'),
    register_transfer('T5001/2025', prop_demo_10, thabo, lerato,
                      '2025-03-01', 1200000, ROk),
    print_result(ROk),
    nl,
    print_title_chain(prop_demo_10),
    print_encumbrances(prop_demo_10),
    writeln('==========================================================='),
    writeln('  End of demo. All data above is fictional.'),
    writeln('===========================================================') .

section(Title) :-
    nl,
    writeln('==========================================================='),
    format('  ~w~n', [Title]),
    writeln('==========================================================='),
    nl.
